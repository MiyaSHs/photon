#!/usr/bin/env bash
# build_proxy_shaders.sh: the proxy's own small shaders (T4.2 full-screen passes) -> bytecode embedded as C arrays in
# src/proxy_shaderapi/shaders/<name>.h (committed: our own code compiled, nothing from stock). Uses the same native d3dcompiler_47
# under Wine as build_shaders.sh. Run after editing a .hlsl there.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
source "$ROOT/scripts/env.sh"
export WINEDLLOVERRIDES="mscoree,mshtml=;d3dcompiler_47=n;d3dcompiler_43=n"
TOOL=$ROOT/build/tools/d3dcompile/d3dcompile.exe
DLL=${D3DCOMPILER:-$GMOD_BIN/d3dcompiler_47.dll}
D=$ROOT/src/proxy_shaderapi/shaders
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
# the dev box on WSL (2026-11-11): no Wine; the tool runs natively on Windows with the system's d3dcompiler_47 (the same DLL version)
if ! command -v wine >/dev/null && command -v wslpath >/dev/null; then
  RUN=(); wp() { wslpath -w "$1"; }; DLL=${D3DCOMPILER:-/mnt/c/Windows/System32/d3dcompiler_47.dll}
  T=$(mktemp -d -p /mnt/c/Users/Public photon_fxc.XXXX); trap 'rm -rf "$T"' EXIT   # a Windows path: the exe writes there
else
  RUN=(wine); wp() { winepath -w "$1"; }
fi
build() {   # name profile
  "${RUN[@]}" "$TOOL" "$(wp "$DLL")" "$(wp "$D/$1.hlsl")" main "$2" "$(wp "$T/$1.bin")" "$(wp "$T/$1.asm")" >/dev/null 2>"$T/$1.err" </dev/null \
    || { cat "$T/$1.err"; exit 1; }
  python3 -I - "$T/$1.bin" "$D/$1.h" "$1" <<'PY'
import sys
b = open(sys.argv[1], 'rb').read()
name = sys.argv[3]
with open(sys.argv[2], 'w') as f:
    f.write(f'/* generated by scripts/build_proxy_shaders.sh from {name}.hlsl: do not edit */\n')
    f.write(f'static const DWORD k_{name}[] = {{\n')
    w = [int.from_bytes(b[i:i+4], 'little') for i in range(0, len(b), 4)]
    for i in range(0, len(w), 8): f.write('    ' + ', '.join(f'0x{x:08x}' for x in w[i:i+8]) + ',\n')
    f.write('};\n')
print(name, len(b), 'bytes')
PY
  grep -c "" "$T/$1.asm" | sed "s/^/  $1 asm lines: /"
}
build shpass_vs vs_3_0
build shdebug_ps ps_3_0
build shnull20_ps ps_2_0
build shnull30_ps ps_3_0
build shadow_ps ps_3_0
build shadow_soft_ps ps_3_0
build lampshadow_ps ps_3_0
build l3ratio_ps ps_3_0
build depthcopy_ps ps_3_0
build outline_ps ps_3_0
build ptrt_comp_ps ps_3_0
build nanite_merge_ps ps_3_0
build worldcast_vs vs_3_0
build worldnrm_vs vs_3_0
build worldnrm_ps ps_3_0
build fog_ps ps_3_0
build worldcastuv_vs vs_3_0
build castalpha_ps ps_3_0
build castalpha20_ps ps_2_0
build taa_ps ps_3_0
build taa_sharpen_ps ps_3_0
build taa_dist_ps ps_3_0
build velocity_vs vs_3_0
build velocity_ps ps_3_0
build upscale_ps ps_3_0
build taau_ps ps_3_0
build fullmv_ps ps_3_0
echo BUILD_PROXY_SHADERS OK
